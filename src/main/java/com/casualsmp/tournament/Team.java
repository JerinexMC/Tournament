package com.casualsmp.tournament;

import org.bukkit.Bukkit;
import org.bukkit.OfflinePlayer;
import org.bukkit.entity.Player;

import java.util.*;

public class Team {

    private final String name;
    private UUID captain;
    private final Set<UUID> members = new LinkedHashSet<>();
    private boolean autoGenerated;

    public Team(String name, UUID captain) {
        this.name = name;
        this.captain = captain;
        if (captain != null) {
            this.members.add(captain);
        }
        this.autoGenerated = false;
    }

    public String getName() {
        return name;
    }

    public UUID getCaptain() {
        return captain;
    }

    public void setCaptain(UUID captain) {
        this.captain = captain;
        if (captain != null) {
            this.members.add(captain);
        }
    }

    public boolean isCaptain(UUID playerId) {
        return captain != null && captain.equals(playerId);
    }

    public Set<UUID> getMembers() {
        return Collections.unmodifiableSet(members);
    }

    public boolean hasMember(UUID playerId) {
        return members.contains(playerId);
    }

    public boolean addMember(UUID playerId) {
        if (playerId == null) return false;
        return members.add(playerId);
    }

    public boolean removeMember(UUID playerId) {
        if (playerId == null) return false;
        boolean removed = members.remove(playerId);
        if (removed && playerId.equals(captain)) {
            captain = members.isEmpty() ? null : members.iterator().next();
        }
        return removed;
    }

    public int size() {
        return members.size();
    }

    public boolean isEmpty() {
        return members.isEmpty();
    }

    public boolean isAutoGenerated() {
        return autoGenerated;
    }

    public void setAutoGenerated(boolean autoGenerated) {
        this.autoGenerated = autoGenerated;
    }

    public List<Player> getOnlineMembers() {
        List<Player> online = new ArrayList<>();
        for (UUID id : members) {
            Player p = Bukkit.getPlayer(id);
            if (p != null && p.isOnline()) {
                online.add(p);
            }
        }
        return online;
    }

    public List<String> getMemberNames() {
        List<String> names = new ArrayList<>();
        for (UUID id : members) {
            Player online = Bukkit.getPlayer(id);
            if (online != null) {
                names.add(online.getName());
            } else {
                OfflinePlayer offline = Bukkit.getOfflinePlayer(id);
                names.add(offline.getName() != null ? offline.getName() : id.toString().substring(0, 8));
            }
        }
        return names;
    }
}
